#!/usr/bin/env python3
"""The documents, from the same sources as the boards: docs/HANDBOOK_<stem>.md (every tile: what it is, what to
cable, what to expect, its Pmod pins), docs/MANUFACTURING.md (how to order each board at JLCPCB with the files in
out/<stem>/, and what it costs), docs/DESIGN_NOTES.md (what was decided and why, the lessons kept).  Run after the
`out` stage:

    python3 scripts/gen_docs.py amod_a

Everything quoted here is read from out/<stem>_tiles.json, out/<stem>/*.csv, scripts/parts.py and the board
modules, so a number in a document is the number on the board.  A claim the sources cannot back is not written.
"""
import csv, datetime, html, importlib, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(ROOT, "boards"))
import parts
import tile_docs

DOCS = os.path.join(ROOT, "docs")
THUMB_MARGIN = 0.9            # scripts/tile_thumbs.py's margin round each tile, mm
BOARDS = {s: (b["name"], b["what"]) for s, b in parts.BOARDS.items()}


def load(stem):
    with open(os.path.join(ROOT, "out", stem + "_tiles.json")) as fh:
        meta = json.load(fh)
    mod = importlib.import_module(stem)
    return meta, mod


def bom(stem):
    path = os.path.join(ROOT, "out", stem, stem + "_bom_costed.csv")
    if not os.path.exists(path):
        return []
    with open(path) as fh:
        return list(csv.DictReader(fh))


def tile_rows(meta):
    for t in sorted(meta["tiles"], key=lambda t: t["idx"]):
        yield t


def pmod_pins(meta):
    """Which tile uses which Pmod line, from the nets the parts' pins carry."""
    out = {}
    for t in meta["tiles"]:
        for p in t["parts"]:
            for pin, net in p["pins"].items():
                if net.startswith("/PMOD") and net != "/PMOD_VCC" and p["key"] != "PMOD":
                    out.setdefault(net, set()).add(t["id"])
    return out


def esc(text):
    return html.escape(text, quote=False)


def thumb_px(t):
    """The picture's width in the handbook: 12 px a millimetre, at most 520 (a three-cell tile)."""
    return min(520, int(round((t["w"] + 2 * THUMB_MARGIN) * 12)))


def where(t, j):
    """A jack's place on its tile in words: top left, bottom right, or the top or bottom of one of its cells."""
    v = "top" if j["y"] < t["h"] / 2 else "bottom"
    n = len(t["cells"])
    if abs(j["x"] - (4.75 if v == "top" else t["w"] - 4.75)) < 1.0 or n == 1:
        return "%s %s" % (v, "left" if j["x"] < t["w"] / 2 else "right")
    if abs(j["x"] - t["w"] / 2) < 1.0:
        return "%s middle" % v
    k = int(j["x"] // 21.5)
    cell = ["left", "right"][k] if n == 2 else ["left", "middle", "right"][k]
    return "%s of the %s cell" % (v, cell)


def readme_block(stem, meta):
    """The README's table for one board: a row a tile, a summary of its handbook entry with a link to it."""
    name, what = BOARDS[stem]
    docs = tile_docs.DOCS.get(stem, {})
    def cell(text):
        return esc(text or "").replace("|", "\\|")
    out = ["### [%s](docs/HANDBOOK_%s.md): %s" % (name, stem, what), "",
           '<img src="docs/images/%s-render-top.png" width="95%%">' % stem, "",
           "| tile | what it does | chip | specs | limits | experiments | how to use it | you need |",
           "|---|---|---|---|---|---|---|---|"]
    for t in tile_rows(meta):
        d = docs.get(t["id"], {})
        chips = ", ".join("[%s](%s)" % (c, tile_docs.CHIP_URL[c]) for c in d.get("chips", [])) or "passive"
        out.append("| [**%s**](docs/HANDBOOK_%s.md#%s) %s | %s | %s | %s | %s | %s | %s | %s |" % (
            t["id"], stem, t["id"].lower(), cell(t["name"]), cell(d.get("does")), chips, cell(d.get("specs")), cell(d.get("limits")),
            cell(d.get("experiments")), cell(d.get("use")), cell(d.get("needs"))))
    out += ["", "More on each tile, with its picture, in the [%s handbook](docs/HANDBOOK_%s.md); what to buy in [KIT.md](docs/KIT.md)." % (name, stem), ""]
    return out


def readme(stems):
    """Rewrite the README's per-board blocks between their markers; everything else in it is written by hand."""
    path = os.path.join(ROOT, "README.md")
    text = open(path).read()
    for stem in stems:
        meta, mod = load(stem)
        a, b = "<!-- board:%s -->" % stem, "<!-- /board:%s -->" % stem
        if a not in text:
            continue
        i, j = text.index(a) + len(a), text.index(b)
        text = text[:i] + "\n" + "\n".join(readme_block(stem, meta)) + "\n" + text[j:]
    with open(path, "w") as fh:
        fh.write(text)


def handbook(stem, meta, mod):
    name, what = BOARDS[stem]
    lines = ["# %s handbook: %s" % (name, what), "",
             "Generated by `scripts/gen_docs.py` from the tiles' own declarations (`boards/%s.py`); the expected results come from" % stem,
             "the same text the silkscreen quotes.  Rev %s, %s." % (parts.REV, parts.DATE), ""]
    lines += ["## The board", "", "![front](images/%s-render-top.png)" % stem, ""]
    intro = getattr(mod, "HANDBOOK_INTRO", None)
    if intro:
        lines += list(intro) + [""]
    else:
        lines += ["Cells are 20 mm on a 21.5 mm pitch.  A tile's input is its top-left jack and its output its bottom-right jack;",
                  "each jack's name is printed on its own tile's frame, beside it.  Cable the DAC to IN and OUT to the ADC.", ""]
    if getattr(mod, "PMOD_NAMES", None):
        pm = pmod_pins(meta)
        names = getattr(mod, "PMOD_NAMES", {})
        lines += ["### Pmod lines", "", "The 2 x 6 plug on %s (pins 1-4 are IO1-4, 7-10 are IO5-8, 5 and 11 ground, 6 and 12 the FPGA's 3.3 V," % getattr(mod, "PMOD_HOST", "R10's bottom edge"),
                  getattr(mod, "PMOD_VCC_TEXT", "which the board does not use: every chip here runs from its own 3.3 V, so the lines are 3.3 V CMOS both ways):"), ""]
        for net in sorted(pm, key=lambda n: int(n.replace("/PMOD", ""))):
            k = int(net.replace("/PMOD", ""))
            lines.append("- Pmod pin %d (%s): %s, %s" % (k if k <= 4 else k + 2, net.lstrip("/"), names.get(net, ""), ", ".join(sorted(pm[net]))))
        lines.append("")
    for block in getattr(mod, "HANDBOOK_SECTIONS", []):
        lines += list(block) + [""]
    if stem == "amod_a":
        lines += ["Every powered tile has a slide switch along its left edge (slider up: on) feeding a P-FET, so a tile's own rail is",
                  "dead until you switch it on; -5 V is not switched (an op amp with no +5 V draws nothing).  The power tile (A1)",
                  "takes 5 V from its USB-C; its socket along the top edge carries +5, ground, -5, ground, +3.3 V for a breadboard.", ""]
        pm = pmod_pins(meta)
        if pm:
            lines += ["### Pmod lines", "", "The 2 x 6 plug on the bottom edge (pins 1-4 are IO1-4, 7-10 are IO5-8, 5 and 11 ground, 6 and 12 the FPGA's 3.3 V):", ""]
            for net in sorted(pm, key=lambda n: int(n.replace("/PMOD", ""))):
                k = int(net.replace("/PMOD", ""))
                pin = k if k <= 4 else k + 2
                lines.append("- Pmod pin %d (%s): %s" % (pin, net.lstrip("/"), ", ".join(sorted(pm[net]))))
            lines.append("")
    lines += ["## The tiles", "",
              "Each tile in a table: its picture, then what it does, its jacks, what to expect, how to cable it, what to buy",
              "(the links are in [KIT.md](KIT.md)), its numbers and limits, the experiments it is for and the circuit.", ""]
    docs = tile_docs.DOCS.get(stem, {})
    pm = pmod_pins(meta)
    pnames = getattr(mod, "PMOD_NAMES", {}) or {}
    for t in tile_rows(meta):
        d = docs.get(t["id"], {})
        title = "%s  %s%s" % (t["id"], t["name"], (", " + t["subtitle"]) if t["subtitle"] else "")
        lines += ['<a id="%s"></a>' % t["id"].lower(), "", "### " + title, ""]
        rows = []
        def row(label, text, raw=False):
            if text and text != "-":
                rows.append("<b>%s</b> %s" % (label, text if raw else esc(text)))
        if d.get("does"):
            rows.append("<b>%s</b>" % esc(d["does"]))
        if t["jacks"]:
            js = []
            for j in t["jacks"]:
                lim = (" (%s)" % j["limit"]) if j.get("limit") else ""
                js.append("%s, %s%s" % (j.get("silk") or j["label"], where(t, j), lim))
            row("Jacks:", "; ".join(js) + ".")
        pins = []
        for net in sorted(pm, key=lambda n: int(n.replace("/PMOD", ""))):
            if t["id"] in pm[net]:
                k = int(net.replace("/PMOD", ""))
                pins.append("IO%d (Pmod pin %d)%s" % (k, k if k <= 4 else k + 2, (": " + pnames[net]) if pnames.get(net) else ""))
        row("Pmod:", "; ".join(pins))
        row("Supply:", t.get("supply") or "")
        row("Expect:", t.get("result", ""))
        row("How to use it:", d.get("use", ""))
        if d.get("needs"):
            row("You need:", esc(d["needs"]) + ' (<a href="KIT.md">KIT.md</a>)' if "kit" in d["needs"].lower() else esc(d["needs"]), raw=True)
        row("Specs:", d.get("specs", ""))
        row("Limits:", d.get("limits", ""))
        row("Experiments:", d.get("experiments", ""))
        if d.get("chips"):
            row("Chip:", ", ".join('<a href="%s">%s</a>' % (tile_docs.CHIP_URL[c], esc(c)) for c in d["chips"]), raw=True)
        if t["sections"]:
            row("Tutorial pages:", "; ".join(t["sections"]) + ".")
        notes = t.get("notes") or []
        row("The circuit:", " ".join(notes))
        chips = sorted({p["key"] for p in t["parts"] if p["key"] in parts.PARTS and parts.PARTS[p["key"]].get("process", "SMT") == "SMT"
                        and p["key"] not in ("SMA", "TP", "SW_SLIDE", "PFET")})
        if chips:
            row("Parts:", ", ".join("%s (%s)" % (parts.PARTS[k]["mpn"], parts.PARTS[k]["lcsc"]) for k in chips) + ".")
        px = thumb_px(t)
        lines += ['<table><tr>',
                  '<td valign="top" width="%d"><img src="images/tiles/%s_%s.jpg" width="%d" alt="%s"></td>' % (px + 8, stem, t["id"], px, esc(title)),
                  '<td valign="top">', "", "<br><br>\n".join(rows), "", "</td></tr></table>", ""]
    lines += ["## Ground, loops and probing", "",
              "%s ground loops stand in the margins; every tile's loops are on the signal they name.  The RH-5019" % (
                  ["No", "One", "Two", "Three", "Four", "Five", "Six"][min(len(meta.get("gnd_loops", [])), 6)]),
              "loops take a scope's grabber.  The SMA jacks are 50 ohm; where an input is not 50 ohm the jack's silk says so.", ""]
    with open(os.path.join(DOCS, "HANDBOOK_%s.md" % stem), "w") as fh:
        fh.write("\n".join(lines))


def manufacturing(stems):
    lines = ["# Manufacturing: ordering the boards at JLCPCB", "",
             "Generated by `scripts/gen_docs.py` from the fab packages in `out/`.  Rev %s, %s.  Five boards of each, two" % (parts.REV, parts.DATE),
             "assembled, is the order Appendix D asked for; the cost lines below are the parts of one assembled board at JLCPCB's",
             "unit prices on the day the stock was checked (`scripts/jlc_cache.json` has the time of every answer).", ""]
    for stem in stems:
        name, what = BOARDS[stem]
        out = os.path.join(ROOT, "out", stem)
        if not os.path.isdir(out):
            lines += ["## %s: not built yet" % name, ""]
            continue
        rows = bom(stem)
        total = sum(float(r.get("Ext $", 0) or 0) for r in rows)
        ext = sum(1 for r in rows if r.get("JLC") == "extended")
        meta, mod = load(stem)
        layers = getattr(mod, "LAYERS", 2)
        lines += ["## %s: %s" % (name, what), "",
                  "- Gerbers and drills: `out/%s/%s-gerbers.zip` (upload as the PCB file)." % (stem, stem),
                  "- Board: 100 x 100 mm, %d layers, 1.6 mm, JLCPCB's standard stack%s." % (layers, " (JLC04161H-7628 for the RF lines)" if parts.BOARDS[stem].get("rf") else ""),
                  "- BOM: `out/%s/%s_bom_jlcpcb_upload.csv`; placements: `out/%s/%s_cpl_jlcpcb_upload.csv` (rotations already turned" % (stem, stem, stem, stem),
                  "  for JLCPCB's conventions; the native KiCad file is beside it)." ,
                  "- Assembly: top side only, every part from JLCPCB's shelf, nothing hand-soldered.  %d BOM lines, %d of them" % (len(rows), ext),
                  "  extended parts (each adds JLCPCB's loading fee).",
                  "- Parts per board: $%.2f.  Read `out/%s/%s-assembly-notes.txt` before confirming the order." % (total, stem, stem), ""]
        lines += ["### Order steps", "",
                  "1. Order now > PCB: upload the gerber zip; 100 x 100 mm, %d layers, 1.6 mm, any colour, HASL or ENIG, 5 pieces." % layers,
                  "2. PCB assembly: economic, top side, 2 pieces; upload the BOM and placement files; confirm the parts list (check",
                  "   every line against the notes: the DIP switches and the LEDs have printed orientation, the SMA and terminals are",
                  "   through-hole and must be selected for assembly).",
                  "3. Check the placement preview against `docs/images/%s-render-top.png`: polarised parts (diodes, LEDs, ICs' pin 1)." % stem,
                  "4. Pay; keep the order number in the chat log.", ""]
    with open(os.path.join(DOCS, "MANUFACTURING.md"), "w") as fh:
        fh.write("\n".join(lines))


def design_notes(stems):
    lines = ["# Design notes", "",
             "What the boards are and why they are the way they are, in one place; the decisions with reasons are in `PLAN.md`,",
             "the night's record in `CLAUDE_CODE_CHAT.md`, the general lessons in `~/OpticsPCBs/CLAUDE_PCB.md`.  Rev %s, %s." % (parts.REV, parts.DATE), ""]
    for stem in stems:
        name, what = BOARDS[stem]
        try:
            meta, mod = load(stem)
        except Exception:
            lines += ["## %s: not built yet" % name, ""]
            continue
        n_parts = sum(len(t["parts"]) for t in meta["tiles"])
        n_jacks = sum(len(t["jacks"]) for t in meta["tiles"])
        lines += ["## %s: %s" % (name, what), "",
                  "%d tiles, %d jacks, %d parts.  %s" % (len(meta["tiles"]), n_jacks, n_parts, (mod.__doc__ or "").strip().replace("\n", " ")), ""]
        for t in tile_rows(meta):
            doc = ""
            fn = getattr(mod, "tile_" + t["id"].lower(), None)
            if fn and fn.__doc__:
                doc = " ".join(l.strip() for l in fn.__doc__.strip().splitlines())
            lines += ["- **%s %s**: %s" % (t["id"], t["name"], doc)]
        lines.append("")
    with open(os.path.join(DOCS, "DESIGN_NOTES.md"), "w") as fh:
        fh.write("\n".join(lines))


def main():
    stem = sys.argv[1] if len(sys.argv) > 1 else "amod_a"
    os.makedirs(DOCS, exist_ok=True)
    meta, mod = load(stem)
    handbook(stem, meta, mod)
    built = [s for s in BOARDS if os.path.exists(os.path.join(ROOT, "out", s + "_tiles.json"))]
    manufacturing(built)
    design_notes(built)
    readme(built)
    print("  wrote docs/HANDBOOK_%s.md, docs/MANUFACTURING.md, docs/DESIGN_NOTES.md, the README's tables" % stem)


if __name__ == "__main__":
    main()
