def l_4x4():
    """A 4 x 4 x 3 mm shielded inductor (the boost's XRNR4030)."""
    return "L_4x4.wrl", HEAD + box(0, 0, 1.5, 4.0, 4.0, 3.0, BLACK)


def main():
    os.makedirs(OUT, exist_ok=True)
    makers = [sma_vertical, lambda: dip(2), lambda: dip(4), lambda: dip(6), lambda: kf301(2), lambda: kf301(3), testloop, pmod_plug, led_0805,
              kcr455, crystal_hc49s, pd70, led_side, pj320a, filt1411, filt2012, slide, wson8_2x2, dfn8_2x2, fuse_1812, l_4x4, qfn32_5x5, lfcsp8_2x3]
    for mk in makers:
        name, body = mk()
        with open(os.path.join(OUT, name), "w") as fh:
            fh.write(body)
    import shutil
    src = os.path.join(HERE, "vendored", "USB_C_Receptacle_HRO_TYPE-C-31-M-12.wrl")
    if os.path.exists(src):
        shutil.copy(src, os.path.join(OUT, "USB_C_Receptacle_HRO_TYPE-C-31-M-12.wrl"))
    print("  wrote %d models to %s" % (len(makers) + 1, os.path.relpath(OUT)))


if __name__ == "__main__":
    main()
