def pj320a():
    s = HEAD + box(-2.0, 0, 2.5, 14.4, 6.1, 5.0, BLACK) + prism_x(-9.2, -8.0, 0, 2.5, 1.8, GREY)
    return "Jack_PJ320A.wrl", s


def filt1411():
    return "Filter_1411.wrl", HEAD + box(0, 0, 0.3, 1.4, 1.1, 0.6, WHITE)


def filt2012():
    return "Filter_2012.wrl", HEAD + box(0, 0, 0.45, 2.0, 1.25, 0.9, WHITE)


def slide():
    s = HEAD + box(0, -0.5, 1.4, 8.0, 2.8, 2.8, SILVER) + box(-1.5, -0.5, 3.1, 1.5, 1.5, 0.8, BLACK)
